      <h2 id="s6"><span class="num">06</span>Почему это особенно строго для АЭС и ТЭС</h2>
      <p>Для поставок на объекты атомной и тепловой энергетики требования к контролю и прослеживаемости, как правило, выше, чем на промышленных трубопроводах общего назначения — это напрямую влияет на объём неразрушающего контроля и состав пакета документов. Подробнее о том, чем такие поставки отличаются от типового заказа, — в статье <a href="<?php echo esc_url( promen_article_url( 'postavka-aes-tes' ) ); ?>">«Поставки для АЭС и ТЭС»</a>, а базовая логика нормативных документов, которые определяют объём контроля, разобрана в статье про <a href="<?php echo esc_url( promen_article_url( 'normativnaya-baza' ) ); ?>">ГОСТ, ОСТ и ТУ на СДТ</a>.</p>

