      <h2 id="s2"><span class="num">02</span>Входной контроль и сертификаты на металл</h2>
      <p>Прежде чем заготовка попадёт в цех, инженер ОТК сверяет сопроводительный сертификат качества с фактической маркировкой партии металла и требованиями спецификации — химический состав, механические свойства, соответствие марки стали нормативному документу объекта. Подробнее о том, как подбирается сама марка стали под параметры трубопровода, — в статье <a href="<?php echo esc_url( promen_article_url( 'vybor-stali' ) ); ?>">«Как выбрать сталь для СДТ»</a>.</p>

      <h2 id="s3"><span class="num">03</span>Идентификация плавки — основа прослеживаемости</h2>
      <p>Номер плавки присваивается заготовке на входном контроле и сопровождает деталь через все этапы производства — от заготовки до готового изделия. Для объектов АЭС-класса это требование не формальность: прослеживаемость плавки должна сохраняться вплоть до маркировки готовой детали и указываться в паспорте изделия.</p>

      <div class="ar-callout">
        <span class="ar-callout-lbl">Важно</span>
        <p>Если номер плавки теряется на любом из этапов, деталь не может быть принята ОТК — независимо от того, насколько она соответствует чертежу геометрически. Прослеживаемость — отдельное требование, а не следствие качества изготовления.</p>
      </div>

      <h2 id="s4"><span class="num">04</span>ВИК и неразрушающий контроль сварных швов</h2>
      <p>Визуально-измерительный контроль — первый рубеж: инженер проверяет поверхность детали и геометрию невооружённым глазом и мерительным инструментом. Для сварных деталей — например, сварных отводов, о которых мы писали в статье <a href="<?php echo esc_url( promen_article_url( 'otvod-svarnoy-besshovnyy' ) ); ?>">«Бесшовные и сварные отводы»</a>, — этого недостаточно: каждый шов дополнительно проходит ультразвуковой (УЗК) или радиографический (РК) контроль, который выявляет внутренние дефекты, не видимые на поверхности.</p>
      <p>Объём и метод неразрушающего контроля определяются не по умолчанию, а нормативным документом объекта — для АЭС-класса требования, как правило, строже, чем для промышленных трубопроводов общего назначения.</p>

      <h3>Пять методов и что каждый из них находит</h3>
      <p>Методы неразрушающего контроля не взаимозаменяемы: каждый «видит» свой класс дефектов. Разделение проходит по глубине залегания несплошности — то, что выходит на поверхность, и то, что лежит в теле металла, выявляется разными методами.</p>

      <div class="ar-table">
        <div class="ar-row"><span class="k">ВИК — визуально-измерительный</span><span class="v">Геометрия детали, форма и размеры шва, видимые дефекты поверхности. Предшествует остальным видам контроля: без него не имеет смысла ни один инструментальный метод.</span></div>
        <div class="ar-row"><span class="k">УЗК — ультразвуковой<br><em>ГОСТ Р 55724-2013</em></span><span class="v">Внутренние несплошности сварного шва и околошовной зоны. Основной метод для толстостенных деталей: не требует доступа к шву с двух сторон и даёт результат сразу, без проявки плёнки.</span></div>
        <div class="ar-row"><span class="k">РК — радиографический<br><em>ГОСТ 7512-82</em></span><span class="v">Трещины, непровары, поры, шлаковые, вольфрамовые и оксидные включения при толщине элементов от 1 до 400 мм; прожоги, подрезы, оценка выпуклости и вогнутости корня шва. Оставляет документальный снимок, который подшивается к делу изделия.</span></div>
        <div class="ar-row"><span class="k">МПД — магнитопорошковый<br><em>ГОСТ 21105-87</em></span><span class="v">Поверхностные и подповерхностные дефекты. Применим только к ферромагнитным материалам — углеродистым и большинству легированных сталей, но не к аустенитным.</span></div>
        <div class="ar-row"><span class="k">ПВК — капиллярный<br><em>ГОСТ 18442-80</em></span><span class="v">Дефекты, выходящие на поверхность, на объектах любых размеров и форм — из чёрных и цветных металлов и сплавов, пластмасс, стекла, керамики.</span></div>
      </div>

      <p>Выбор между МПД и ПВК — не вопрос удобства цеха. ГОСТ 18442-80 оговаривает это прямо: капиллярный контроль применяют к ферромагнитным материалам тогда, когда их магнитные свойства, форма детали, вид и расположение дефектов не позволяют получить магнитопорошковым методом чувствительность, требуемую по ГОСТ 21105-87, либо когда МПД не допускается условиями эксплуатации объекта. Для деталей из аустенитных марок — 08Х18Н10Т, 12Х18Н10Т — вопрос снимается сам собой: аустенит немагнитен, и магнитопорошковый метод к нему неприменим в принципе.</p>

      <div class="ar-callout">
        <span class="ar-callout-lbl">АЭС-класс</span>
        <p>Для оборудования и трубопроводов атомных установок общепромышленные стандарты контроля не применяются напрямую — действует отдельная серия унифицированных методик ГОСТ Р 50.05 «Система оценки соответствия в области использования атомной энергии». Ультразвуковой контроль сварных соединений и наплавленных покрытий выполняется по ГОСТ Р 50.05.02-2018 (введён в действие 01.03.2018 приказом Росстандарта № 99-ст от 27.02.2018), контроль основных материалов и полуфабрикатов — по ГОСТ Р 50.05.05-2018. Эта серия заменила ранее действовавшие ПНАЭ Г-7-030-91.</p>
      </div>

