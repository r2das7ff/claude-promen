      <section class="pol-chapter" id="ch5">
        <h2 class="pol-h2"><span class="pol-h2-num">05</span>Порядок и условия обработки персональных данных</h2>

        <h3 class="pol-h3" id="ch5-1">Принципы обработки персональных данных</h3>
        <ol class="pol-list-num">
          <li>обработка персональных данных осуществляется на законной и справедливой основе;</li>
          <li>обработка ограничивается достижением конкретных, заранее определённых и законных целей;
            не допускается обработка, несовместимая с целями сбора;</li>
          <li>не допускается объединение баз данных, обработка которых осуществляется в несовместимых
            между собой целях;</li>
          <li>обработке подлежат только данные, которые отвечают целям их обработки;</li>
          <li>содержание и объём обрабатываемых данных соответствуют заявленным целям и не избыточны
            по отношению к ним;</li>
          <li>обеспечиваются точность, достаточность и — в необходимых случаях — актуальность данных;
            Общество принимает меры по удалению или уточнению неполных или неточных данных;</li>
          <li>хранение осуществляется не дольше, чем этого требуют цели обработки, если иной срок
            не установлен федеральным законом или договором; по достижении целей данные подлежат уничтожению.</li>
        </ol>

        <h3 class="pol-h3" id="ch5-2">Условия обработки специальных категорий</h3>
        <p class="pol-p">Обработка специальных категорий персональных данных осуществляется Обществом
          с соблюдением следующих условий:</p>
        <ul class="pol-list">
          <li>обработка данных о судимости — государственными или муниципальными органами в пределах
            установленных полномочий, а также иными лицами в случаях, определяемых федеральными законами;</li>
          <li>обработка осуществляется в соответствии с законодательством РФ о гражданстве;</li>
          <li>обработка осуществляется в соответствии с законодательством о государственной социальной
            помощи, трудовым и пенсионным законодательством РФ;</li>
          <li>субъект персональных данных дал согласие в письменной форме;</li>
          <li>обработка осуществляется в соответствии с законодательством об обороне, безопасности,
            противодействии терроризму, транспортной безопасности, противодействии коррупции,
            оперативно-розыскной деятельности, исполнительном производстве, уголовно-исполнительным
            законодательством РФ;</li>
          <li>обработка осуществляется органами прокуратуры в связи с прокурорским надзором;</li>
          <li>обработка осуществляется по поручению другого лица.</li>
        </ul>

        <h3 class="pol-h3" id="ch5-3">Условия обработки иных категорий</h3>
        <ul class="pol-list">
          <li>обработка необходима для достижения целей, предусмотренных международным договором РФ
            или законом, для выполнения возложенных на оператора функций, полномочий и обязанностей;</li>
          <li>обработка осуществляется с согласия субъекта персональных данных;</li>
          <li>обработка необходима для исполнения или заключения договора, стороной/выгодоприобретателем/
            поручителем которого является субъект; договор не может ограничивать права субъекта или
            допускать обработку данных несовершеннолетних, если иное не предусмотрено законом;</li>
          <li>обработка осуществляется по поручению другого лица.</li>
        </ul>

        <h3 class="pol-h3" id="ch5-4">Поручение обработки персональных данных</h3>
        <p class="pol-p">Общество вправе поручить обработку персональных данных другому лицу с согласия субъекта,
          если иное не предусмотрено федеральным законом, на основании заключаемого договора — в том числе
          государственного или муниципального контракта.</p>
        <p class="pol-p">Лицо, осуществляющее обработку по поручению Общества, соблюдает принципы и правила
          обработки, предусмотренные настоящей Политикой, соблюдает конфиденциальность и принимает необходимые
          меры по обеспечению выполнения обязанностей, предусмотренных ФЗ «О персональных данных». Поручение
          определяет перечень персональных данных, перечень действий, способы и цели обработки, требования
          к защите данных и обязанность по запросу Общества предоставлять подтверждающие документы.</p>
        <p class="pol-p">Ответственность перед субъектом персональных данных за действия поручаемого лица несёт
          Общество; поручаемое лицо несёт ответственность перед Обществом. Если поручение дано иностранному
          физическому или юридическому лицу, ответственность несут Общество и это лицо совместно.</p>

        <h3 class="pol-h3" id="ch5-5">Передача персональных данных</h3>
        <p class="pol-p">Общество вправе передавать персональные данные органам дознания и следствия, иным
          уполномоченным органам по основаниям, предусмотренным действующим законодательством РФ.</p>

        <h3 class="pol-h3" id="ch5-6">Конфиденциальность персональных данных</h3>
        <p class="pol-p">Сотрудники Общества, получившие доступ к персональным данным, не раскрывают их третьим
          лицам и не распространяют без согласия субъекта, если иное не предусмотрено федеральным законом.</p>

        <h3 class="pol-h3" id="ch5-7">Согласие субъекта на обработку данных</h3>
        <p class="pol-p">Субъект принимает решение о предоставлении своих данных и даёт согласие на их обработку
          свободно, своей волей и в своём интересе. Согласие должно быть конкретным, предметным,
          информированным, сознательным и однозначным; может быть дано в любой позволяющей подтвердить факт
          его получения форме, если иное не установлено федеральным законом.</p>
        <p class="pol-p">Согласие может быть отозвано субъектом в любой момент. При отзыве Общество вправе
          продолжить обработку без согласия при наличии оснований, указанных в п. 2–11 ч. 1 ст. 6, п. 2–10
          ч. 2 ст. 10 и ч. 2 ст. 11 ФЗ «О персональных данных». Обязанность доказать наличие согласия
          или соответствующего основания лежит на Обществе.</p>
        <p class="pol-p">Согласие в письменной форме субъекта персональных данных должно включать, в частности:</p>
        <ul class="pol-list">
          <li>ФИО, адрес субъекта, реквизиты документа, удостоверяющего личность;</li>
          <li>сведения о представителе субъекта (при получении согласия от представителя);</li>
          <li>наименование и адрес Общества;</li>
          <li>цель обработки персональных данных;</li>
          <li>перечень персональных данных, на обработку которых даётся согласие;</li>
          <li>сведения о лице, осуществляющем обработку по поручению Общества (если применимо);</li>
          <li>перечень действий с персональными данными и общее описание способов обработки;</li>
          <li>срок действия согласия и способ его отзыва;</li>
          <li>подпись субъекта персональных данных.</li>
        </ul>
        <p class="pol-p">В случае недееспособности субъекта согласие даёт его законный представитель; в случае
          смерти субъекта — его наследники, если согласие не было дано при жизни.</p>

        <h3 class="pol-h3" id="ch5-8">Трансграничная передача персональных данных</h3>
        <div class="pol-note"><b>Трансграничная передача персональных данных Обществом не осуществляется.</b></div>

        <h3 class="pol-h3" id="ch5-9">Обработка без использования средств автоматизации</h3>
        <p class="pol-p">Обработка персональных данных считается неавтоматизированной, если действия с данными
          в отношении каждого субъекта осуществляются при непосредственном участии человека.</p>
        <p class="pol-p">Персональные данные при такой обработке обособляются от иной информации — путём фиксации
          на отдельных материальных носителях, в специальных разделах или на полях форм (бланков). Не допускается
          фиксация на одном носителе данных, цели обработки которых заведомо не совместимы; для каждой категории
          используется отдельный материальный носитель.</p>
        <p class="pol-p">Сотрудники, осуществляющие такую обработку, проинформированы о факте обработки, категориях
          данных и правилах обработки, установленных нормативными актами и локальными актами Общества.</p>
        <p class="pol-p">Типовые формы документов, допускающие включение персональных данных, должны: содержать
          сведения о цели обработки, реквизиты Общества и субъекта, источник получения данных, сроки и перечень
          действий; предусматривать поле для отметки о согласии; позволять субъекту ознакомиться со своими
          данными без нарушения прав иных субъектов; исключать объединение полей с несовместимыми целями обработки.</p>
        <p class="pol-p">Обработка организована так, чтобы для каждой категории данных можно было определить
          места хранения материальных носителей и перечень лиц, имеющих к ним доступ; обеспечивается раздельное
          хранение данных, обрабатываемых в разных целях, и условия, исключающие несанкционированный доступ.</p>
      </section>

