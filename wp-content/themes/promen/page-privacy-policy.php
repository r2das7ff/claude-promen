        <h2 class="pol-h2"><span class="pol-h2-num">01</span>Общие положения</h2>

        <h3 class="pol-h3" id="ch1-1">Назначение Политики</h3>
        <p class="pol-p">Настоящая Политика Общества с ограниченной ответственностью Завод «Промышленная Энергетика»
          в отношении обработки персональных данных (далее — Политика) разработана в соответствии с Федеральным
          законом от 27 июля 2006 года № 152-ФЗ «О персональных данных».</p>
        <p class="pol-p">Политика вступает в силу с момента её утверждения Генеральным директором ООО Завод
          «ПромЭнергетика» и подлежит пересмотру в ходе периодического анализа со стороны руководства
          ООО Завод «ПромЭнергетика» (далее — Общество), а также в случаях изменения законодательства
          Российской Федерации в области персональных данных.</p>

        <h3 class="pol-h3" id="ch1-2">Цели политики</h3>
        <p class="pol-p">1.1. Целью Политики является обеспечение защиты прав и свобод субъектов персональных данных
          при обработке их персональных данных Обществом.</p>

        <h3 class="pol-h3" id="ch1-3">Основные понятия</h3>
        <p class="pol-p">1.2. Для целей Политики используются следующие понятия:</p>
        <div class="pol-term">
          <div class="pol-term-row"><span class="pol-term-k">Персональные данные (ПДн)</span><span class="pol-term-v">любая информация, относящаяся к прямо или косвенно определённому, или определяемому физическому лицу (субъекту персональных данных).</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Персональные данные, разрешённые для распространения</span><span class="pol-term-v">персональные данные, доступ неограниченного круга лиц к которым предоставлен субъектом путём дачи согласия в порядке, предусмотренном Федеральным законом «О персональных данных».</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Субъект персональных данных</span><span class="pol-term-v">физическое лицо, которое прямо или косвенно определено или определяемо с помощью персональных данных.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Оператор</span><span class="pol-term-v">государственный орган, муниципальный орган, юридическое или физическое лицо, организующее и (или) осуществляющее обработку персональных данных, а также определяющее цели обработки, состав данных и действия с ними.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Обработка персональных данных</span><span class="pol-term-v">любое действие (операция) или совокупность действий с персональными данными, совершаемых с использованием средств автоматизации или без них — в том числе сбор, запись, систематизация, накопление, хранение, уточнение (обновление, изменение), извлечение, использование, передача (распространение, предоставление, доступ), обезличивание, блокирование, удаление, уничтожение.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Автоматизированная обработка ПДн</span><span class="pol-term-v">обработка персональных данных с помощью средств вычислительной техники.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Распространение персональных данных</span><span class="pol-term-v">действия, направленные на раскрытие персональных данных неопределённому кругу лиц.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Предоставление персональных данных</span><span class="pol-term-v">действия, направленные на раскрытие персональных данных определённому лицу или определённому кругу лиц.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Блокирование персональных данных</span><span class="pol-term-v">временное прекращение обработки персональных данных (за исключением случаев, если обработка необходима для уточнения персональных данных).</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Уничтожение персональных данных</span><span class="pol-term-v">действия, в результате которых становится невозможным восстановить содержание персональных данных в информационной системе персональных данных и (или) в результате которых уничтожаются материальные носители персональных данных.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Информационная система персональных данных (ИСПДн)</span><span class="pol-term-v">совокупность содержащихся в базах данных персональных данных и обеспечивающих их обработку информационных технологий и технических средств.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Конфиденциальность информации</span><span class="pol-term-v">обязательное для лица, получившего доступ к информации, требование не передавать такую информацию третьим лицам без согласия её обладателя.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Трансграничная передача персональных данных</span><span class="pol-term-v">передача персональных данных на территорию иностранного государства органу власти иностранного государства, иностранному физическому или юридическому лицу.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Угрозы безопасности персональных данных</span><span class="pol-term-v">совокупность условий и факторов, создающих опасность несанкционированного, в том числе случайного, доступа к персональным данным, результатом которого могут стать их уничтожение, изменение, блокирование, копирование, предоставление, распространение, а также иные неправомерные действия при обработке в ИСПДн.</span></div>
          <div class="pol-term-row"><span class="pol-term-k">Уровень защищённости персональных данных</span><span class="pol-term-v">комплексный показатель, характеризующий требования, исполнение которых обеспечивает нейтрализацию определённых угроз безопасности персональных данных при их обработке в ИСПДн.</span></div>
        </div>

        <h3 class="pol-h3" id="ch1-4">Область действия</h3>
        <p class="pol-p">Положения Политики распространяются на все отношения, связанные с обработкой персональных
          данных, осуществляемой Обществом:</p>
        <ul class="pol-list">
          <li>с использованием средств автоматизации, в том числе в информационно-телекоммуникационных сетях,
            или без использования таких средств, если обработка без использования таких средств соответствует
            характеру действий, совершаемых с использованием средств автоматизации;</li>
          <li>без использования средств автоматизации.</li>
        </ul>
        <p class="pol-p">Настоящей Политикой должны руководствоваться все сотрудники Общества, осуществляющие
          обработку персональных данных или имеющие к ним доступ.</p>
