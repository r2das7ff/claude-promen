      <section class="pol-chapter" id="ch6">
        <h2 class="pol-h2"><span class="pol-h2-num">06</span>Права субъектов и обязанности Общества</h2>

        <h3 class="pol-h3" id="ch6-1">Право субъекта на доступ к его данным</h3>
        <p class="pol-p">Субъект персональных данных имеет право на получение информации, касающейся обработки
          его персональных данных, в том числе: подтверждение факта обработки; правовые основания и цели
          обработки; применяемые способы обработки; наименование и место нахождения Общества; сведения о лицах,
          имеющих доступ к данным; обрабатываемые данные и источник их получения; сроки обработки и хранения;
          порядок осуществления прав субъекта; сведения об осуществлённой или предполагаемой трансграничной
          передаче; сведения о лице, осуществляющем обработку по поручению Общества; иные сведения,
          предусмотренные федеральным законом.</p>

        <h3 class="pol-h3" id="ch6-2">Ограничения права на доступ</h3>
        <p class="pol-p">Субъект не получает запрашиваемую информацию в случаях, если: обработка осуществляется
          в целях обороны, безопасности государства и охраны правопорядка; обработка осуществляется органами,
          задержавшими субъекта по подозрению в преступлении или предъявившими обвинение; обработка
          осуществляется в связи с противодействием легализации доходов и финансированию терроризма; доступ
          субъекта нарушает права третьих лиц; обработка осуществляется в целях транспортной безопасности.</p>
        <p class="pol-p">Запрашиваемая информация предоставляется субъекту в течение <b>10 рабочих дней</b>
          с момента обращения (может быть продлена не более чем на 5 рабочих дней с мотивированным уведомлением).
          Повторный запрос допускается не ранее чем через <b>30 дней</b> после первоначального обращения,
          если иное не установлено законом или договором.</p>

        <h3 class="pol-h3" id="ch6-3">Продвижение товаров и политическая агитация</h3>
        <div class="pol-note">Обработка персональных данных в целях продвижения товаров, работ, услуг на рынке
          путём прямых контактов с потребителем, а также в целях политической агитации Обществом
          <b>не осуществляется.</b></div>

        <h3 class="pol-h3" id="ch6-4">Автоматизированные решения</h3>
        <div class="pol-note">Принятие решений, порождающих юридические последствия для субъекта, на основании
          исключительно автоматизированной обработки персональных данных Обществом <b>не осуществляется.</b></div>

        <h3 class="pol-h3" id="ch6-5">Право на обжалование</h3>
        <p class="pol-p">Если субъект считает, что Общество обрабатывает его данные с нарушением требований
          ФЗ «О персональных данных» или иным образом нарушает его права, субъект вправе обжаловать действия
          или бездействие Общества в уполномоченный орган по защите прав субъектов персональных данных или
          в судебном порядке, включая возмещение убытков и компенсацию морального вреда.</p>

        <h3 class="pol-h3" id="ch6-6">Обязанности Общества при сборе данных</h3>
        <p class="pol-p">При сборе персональных данных Общество предоставляет субъекту по его просьбе
          запрашиваемую информацию в соответствии с ч. 7 ст. 14 ФЗ «О персональных данных» и разъясняет
          юридические последствия отказа предоставить данные или согласие на обработку.</p>
        <p class="pol-p">Если данные получены не от субъекта, до начала обработки Общество предоставляет ему:
          наименование и адрес Общества; цель обработки и её правовое основание; перечень персональных данных;
          предполагаемых пользователей данных; права субъекта; источник получения данных — за исключением
          случаев, когда субъект уже уведомлён, данные получены на основании закона или договора, либо
          раскрытие нарушит права третьих лиц.</p>

        <h3 class="pol-h3" id="ch6-7">Меры по обеспечению безопасности</h3>
        <p class="pol-p">Общество принимает необходимые правовые, организационные и технические меры для защиты
          персональных данных от неправомерного или случайного доступа, уничтожения, изменения, блокирования,
          копирования, предоставления, распространения, а также иных неправомерных действий, в частности:</p>
        <ul class="pol-list">
          <li>определением угроз безопасности персональных данных при их обработке в ИСПДн;</li>
          <li>применением организационных и технических мер, обеспечивающих установленные Правительством РФ
            уровни защищённости персональных данных;</li>
          <li>применением прошедших оценку соответствия средств защиты информации;</li>
          <li>оценкой эффективности мер безопасности до ввода ИСПДн в эксплуатацию;</li>
          <li>учётом машинных носителей персональных данных;</li>
          <li>обнаружением фактов несанкционированного доступа и принятием мер;</li>
          <li>восстановлением данных, модифицированных или уничтоженных вследствие несанкционированного доступа;</li>
          <li>установлением правил доступа и регистрацией всех действий с данными в ИСПДн;</li>
          <li>контролем за принимаемыми мерами безопасности и уровнем защищённости ИСПДн.</li>
        </ul>

        <h3 class="pol-h3" id="ch6-8">Обязанности при обращении субъекта</h3>
        <p class="pol-p">Общество сообщает субъекту или его представителю о наличии его персональных данных
          и предоставляет возможность ознакомления с ними в течение <b>10 рабочих дней</b> с даты обращения
          (продление — не более чем на 5 рабочих дней с мотивированным уведомлением). Отказ в предоставлении
          информации даётся в письменной форме в тот же срок.</p>
        <p class="pol-p">Ознакомление предоставляется безвозмездно. В срок, не превышающий <b>7 рабочих дней</b>
          со дня подтверждения, что данные неполны, неточны или неактуальны, Общество вносит необходимые
          изменения; если данные получены незаконно или не нужны для цели обработки — уничтожает их. Субъект
          и по возможности третьи лица уведомляются о внесённых изменениях.</p>

        <h3 class="pol-h3" id="ch6-9">Устранение нарушений, блокирование и уничтожение</h3>
        <p class="pol-p">При выявлении неправомерной или неточной обработки по обращению субъекта или запросу
          уполномоченного органа Общество блокирует соответствующие данные на период проверки. При подтверждении
          неточности — уточняет данные в течение <b>7 рабочих дней</b> и снимает блокирование.</p>
        <p class="pol-p">При выявлении неправомерной обработки Общество прекращает её не позднее <b>3 рабочих
          дней</b> с даты выявления; если обеспечить правомерность невозможно — уничтожает данные в срок,
          не превышающий <b>10 рабочих дней</b>.</p>
        <p class="pol-p">При достижении цели обработки или отзыве согласия субъектом Общество прекращает
          обработку и уничтожает данные в срок, не превышающий <b>30 дней</b>, если иное не предусмотрено
          договором или законом. При обращении с требованием о прекращении обработки — не позднее
          <b>10 рабочих дней</b> с даты получения требования (продление до 5 рабочих дней). Если уничтожение
          в указанный срок невозможно — данные блокируются, а уничтожение обеспечивается в срок не более
          <b>6 месяцев</b>, если иной срок не установлен федеральными законами.</p>

        <h3 class="pol-h3" id="ch6-10">Уведомление уполномоченного органа об инцидентах</h3>
        <p class="pol-p">В случае неправомерной или случайной передачи персональных данных, повлекшей нарушение
          прав субъектов, Общество уведомляет уполномоченный орган по защите прав субъектов персональных данных:</p>
        <ul class="pol-list">
          <li>в течение <b>24 часов</b> — о произошедшем инциденте, предполагаемых причинах и вреде,
            принятых мерах и лице, ответственном за взаимодействие с уполномоченным органом;</li>
          <li>в течение <b>72 часов</b> — о результатах внутреннего расследования и лицах, действия которых
            стали причиной инцидента (при наличии).</li>
        </ul>

        <h3 class="pol-h3" id="ch6-11">Уведомление о намерении осуществлять обработку</h3>
        <p class="pol-p">Общество, за исключением случаев, предусмотренных федеральным законом, до начала
          обработки уведомляет уполномоченный орган о своём намерении осуществлять обработку персональных данных.
          Уведомление содержит: наименование и адрес Общества; цель обработки; описание мер защиты (включая
          сведения о криптографических средствах); данные ответственного лица; дату начала обработки; срок
          или условие её прекращения; сведения о трансграничной передаче; место нахождения базы данных;
          сведения об обеспечении безопасности данных.</p>
        <p class="pol-p">Об изменении указанных сведений Общество уведомляет уполномоченный орган не позднее
          15-го числа месяца, следующего за месяцем изменений; о прекращении обработки — в течение
          <b>10 рабочих дней</b> с даты прекращения.</p>
      </section>

      <!-- 7 -->
      <section class="pol-chapter" id="ch7">
        <h2 class="pol-h2"><span class="pol-h2-num">07</span>Меры по обеспечению выполнения обязанностей</h2>

        <h3 class="pol-h3" id="ch7-1">Организационные меры</h3>
        <p class="pol-p">Общество самостоятельно определяет состав и перечень мер, необходимых и достаточных
          для обеспечения выполнения обязанностей, если иное не предусмотрено федеральными законами.
          К таким мерам, в частности, относятся:</p>
        <ul class="pol-list">
          <li>назначение ответственного за организацию обработки персональных данных;</li>
          <li>издание Политики и локальных актов по вопросам обработки персональных данных, а также актов,
            направленных на предотвращение и выявление нарушений и устранение их последствий;</li>
          <li>применение правовых, организационных и технических мер по обеспечению безопасности данных;</li>
          <li>осуществление внутреннего контроля и (или) аудита соответствия обработки требованиям к защите
            персональных данных, Политике и локальным актам;</li>
          <li>оценка вреда, который может быть причинён субъектам в случае нарушения ФЗ «О персональных данных»,
            и соотношение этого вреда с принимаемыми мерами;</li>
          <li>ознакомление сотрудников, осуществляющих обработку, с законодательством о персональных данных,
            требованиями к их защите и локальными актами, и (или) их обучение.</li>
        </ul>

        <h3 class="pol-h3" id="ch7-2">Меры безопасности при обработке</h3>
        <p class="pol-p">Обеспечение безопасности персональных данных достигается определением угроз безопасности,
          применением организационных и технических мер защиты, использованием прошедших оценку соответствия
          средств защиты информации, оценкой эффективности мер до ввода ИСПДн в эксплуатацию, учётом машинных
          носителей, обнаружением фактов несанкционированного доступа и восстановлением данных при их утрате,
          установлением правил доступа и контролем за уровнем защищённости информационных систем.</p>
      </section>

      <!-- 8 -->
      <section class="pol-chapter" id="ch8">
        <h2 class="pol-h2"><span class="pol-h2-num">08</span>Сферы ответственности</h2>

        <h3 class="pol-h3" id="ch8-1">Ответственный за организацию обработки</h3>
        <p class="pol-p">Общество назначает лицо, ответственное за организацию обработки персональных данных.
          Это лицо получает указания непосредственно от исполнительного органа Общества и подотчётно ему.
          Общество предоставляет ему необходимые сведения. В частности, ответственное лицо:</p>
        <ul class="pol-list">
          <li>осуществляет внутренний контроль за соблюдением Обществом и сотрудниками законодательства РФ
            о персональных данных, в том числе требований к их защите;</li>
          <li>доводит до сведения сотрудников положения законодательства, локальных актов и требований
            к защите персональных данных;</li>
          <li>организует приём и обработку обращений и запросов субъектов персональных данных или их
            представителей и (или) контролирует приём и обработку таких обращений.</li>
        </ul>

        <h3 class="pol-h3" id="ch8-2">Ответственность</h3>
        <p class="pol-p">Лица, виновные в нарушении требований Федерального закона «О персональных данных»,
          несут предусмотренную законодательством Российской Федерации ответственность.</p>
        <p class="pol-p">Моральный вред, причинённый субъекту персональных данных вследствие нарушения его прав,
          правил обработки персональных данных или требований к их защите, подлежит возмещению в соответствии
          с законодательством РФ независимо от возмещения имущественного вреда и понесённых субъектом убытков.</p>
      </section>

