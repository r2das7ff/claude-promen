          <li>договоры, заключаемые между оператором и субъектом персональных данных;</li>
          <li>согласия субъектов персональных данных на обработку их персональных данных.</li>
        </ol>

        <h3 class="pol-h3" id="ch3-2">Сроки и прекращение обработки</h3>
        <p class="pol-p">В случаях, прямо не предусмотренных законодательством РФ, но соответствующих полномочиям
          Общества, обработка персональных данных осуществляется с согласия субъекта. Обработка прекращается
          при реорганизации или ликвидации Общества.</p>
        <p class="pol-p">Обработка данных по гражданско-правовому договору осуществляется в течение срока его
          исполнения, а также в течение срока исковой давности — <b>трёх (3) лет</b> после исполнения. По истечении
          срока исковой давности при отсутствии претензий субъекта такие данные уничтожаются.</p>
        <p class="pol-p">Условием прекращения обработки может являться достижение целей обработки, истечение
          срока действия согласия, отзыв согласия субъектом или требование о прекращении обработки, а также
          выявление неправомерной обработки.</p>

        <h3 class="pol-h3" id="ch3-3">Специальные категории данных</h3>
        <p class="pol-p">Общество не осуществляет обработку специальных категорий персональных данных
          и биометрических персональных данных.</p>
