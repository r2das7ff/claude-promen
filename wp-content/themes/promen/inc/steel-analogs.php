/**
 * Идентификатор марки для адреса (?marka=…): транслит в духе слагов
 * фильтра каталога — 12Х18Н10Т → 12h18n10t, Ст3сп → st3sp.
 */
function promen_steel_analog_id( string $name ): string {
	$map = [
		'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'е' => 'e', 'ё' => 'e', 'ж' => 'zh',
		'з' => 'z', 'и' => 'i', 'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm', 'н' => 'n', 'о' => 'o',
		'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't', 'у' => 'u', 'ф' => 'f', 'х' => 'h', 'ц' => 'c',
		'ч' => 'ch', 'ш' => 'sh', 'щ' => 'sch', 'ы' => 'y', 'э' => 'e', 'ю' => 'yu', 'я' => 'ya', 'ь' => '', 'ъ' => '',
	];
	$s = strtr( mb_strtolower( $name, 'UTF-8' ), $map );
	return trim( (string) preg_replace( '/[^a-z0-9]+/', '-', $s ), '-' );
}

/**
 * Позиции каталога по маркам: [марка (раскодированный слаг) => [n, by[раздел => n]]].
 *
 * Раздел — подкатегория для СДТ (отводы, тройники…), верхняя категория для
 * остальных групп (фланцы, крепёж, трубы): у них свои страницы с фильтром
 * «Сталь». Скан steels_json всего канона — только по кэш-промаху, ключ
 * сбрасывается вместе с фильтрами при пересборке каталога.
 *
 * @return array<string, array{n:int, by:array<string,int>}>
 */
function promen_steel_analog_catalog(): array {
	$ckey = function_exists( 'promen_filters_cache_key' )
		? promen_filters_cache_key( 'steel_analog_cat' )
		: 'promen_steel_analog_cat';
	$cached = get_transient( $ckey );
	if ( is_array( $cached ) ) {
		return $cached;
	}
	if ( ! function_exists( 'promen_catalog_table_name' ) || ! function_exists( 'promen_term_map' ) ) {
		return [];
	}

	$terms = promen_term_map( 'product_cat' );
	$by_id = [];
	foreach ( $terms as $slug => $d ) {
		$by_id[ $d['id'] ] = [ 'slug' => (string) $slug, 'parent' => $d['parent'] ];
	}
	$bucket_of = static function ( string $cat ) use ( $terms, $by_id ): string {
		if ( ! isset( $terms[ $cat ] ) ) {
			return $cat;
		}
		$chain = [ $cat ];
		$pid   = $terms[ $cat ]['parent'];
		while ( $pid && isset( $by_id[ $pid ] ) ) {
			$chain[] = $by_id[ $pid ]['slug'];
			$pid     = $by_id[ $pid ]['parent'];
		}
		$top = end( $chain );
		// СДТ делится по видам деталей, остальные группы — целиком.
		return ( 'sdt' === $top && count( $chain ) > 1 ) ? $chain[ count( $chain ) - 2 ] : $top;
	};

	global $wpdb;
	$table = promen_catalog_table_name();
	// phpcs:ignore WordPress.DB.PreparedSQL
	$rows = $wpdb->get_results( "SELECT category, steels_json FROM {$table} WHERE steels_json IS NOT NULL AND steels_json != '[]'", ARRAY_A );

	$out     = [];
	$buckets = [];
	foreach ( $rows ?: [] as $r ) {
		$cat = (string) $r['category'];
		$b   = $buckets[ $cat ] ??= $bucket_of( $cat );
		foreach ( array_unique( (array) json_decode( (string) $r['steels_json'], true ) ) as $s ) {
			$k = mb_strtolower( rawurldecode( (string) $s ), 'UTF-8' );
			$out[ $k ]['n']        = ( $out[ $k ]['n'] ?? 0 ) + 1;
			$out[ $k ]['by'][ $b ] = ( $out[ $k ]['by'][ $b ] ?? 0 ) + 1;
		}
	}
	set_transient( $ckey, $out, 6 * HOUR_IN_SECONDS );
	return $out;
}

/**
 * Ссылки в каталог для марки: по каждому её слагу — всего и по разделам.
 *
 * @return array<int, array{label:string, n:int, url:string, by:array}>
 */
function promen_steel_analog_links( array $slugs ): array {
	$stats   = promen_steel_analog_catalog();
	$catalog = function_exists( 'wc_get_page_permalink' ) ? wc_get_page_permalink( 'shop' ) : home_url( '/catalog/' );
	$labels  = [];
	foreach ( function_exists( 'promen_term_map' ) ? promen_term_map( 'pa_steel' ) : [] as $slug => $d ) {
		$labels[ mb_strtolower( rawurldecode( (string) $slug ), 'UTF-8' ) ] = $d['name'];
	}
	$cats = function_exists( 'promen_term_map' ) ? promen_term_map( 'product_cat' ) : [];

	$out = [];
	foreach ( $slugs as $slug ) {
		$k  = mb_strtolower( $slug, 'UTF-8' );
		$st = $stats[ $k ] ?? null;
		if ( ! $st || empty( $st['n'] ) ) {
			continue;
		}
		$q  = '?steel=' . rawurlencode( $k );
		$by = [];
		arsort( $st['by'] );
		foreach ( $st['by'] as $b => $n ) {
			$link = function_exists( 'promen_product_cat_link' ) ? promen_product_cat_link( (string) $b ) : '';
			if ( '' === $link || 'uncategorized' === $b ) {
				continue;
			}
			$by[] = [ 'label' => (string) ( $cats[ $b ]['name'] ?? $b ), 'n' => (int) $n, 'url' => $link . $q ];
		}
		$out[] = [
			'label' => (string) ( $labels[ $k ] ?? $slug ),
			'n'     => (int) $st['n'],
			'url'   => $catalog . $q,
			'by'    => $by,
		];
	}
	return $out;
}

/**
 * Марки для страницы: данные подборщика + справочник каталога + ссылки.
 * Порядок — по группам, внутри группы — как в данных.
 *
 * @return array<int, array<string, mixed>>
 */
function promen_steel_analog_grades(): array {
	static $grades = null;
	if ( null !== $grades ) {
		return $grades;
	}
	$ref    = function_exists( 'promen_steel_reference' ) ? promen_steel_reference() : [];
	$groups = array_keys( promen_steel_analog_groups() );
	$grades = [];
	foreach ( promen_steel_analog_data() as $name => $d ) {
		$r    = $ref[ function_exists( 'promen_steel_key' ) ? promen_steel_key( (string) $name ) : $name ] ?? [];
		$mech = $d['mech'] ?? ( $r['mech'] ?? null );
		$grades[] = [
			'id'    => promen_steel_analog_id( (string) $name ),
			'name'  => (string) $name,
			'g'     => $d['g'],
			'desc'  => (string) ( $r['desc'] ?? ( $d['desc'] ?? '' ) ),
			'std'   => (string) ( $r['std'] ?? ( $d['std'] ?? '' ) ),
			'temp'  => (string) ( $r['temp'] ?? '' ),
			'apps'  => array_values( (array) ( $r['apps'] ?? [] ) ),
			'mech'  => $mech ? [ 'st' => $mech['st'] ?? '', 'sv' => $mech['sv'] ?? '', 'delta' => $mech['delta'] ?? '' ] : null,
			'chem'  => $d['chem'] ?? [],
			'an'    => $d['an'] ?? [],
			'none'  => (string) ( $d['none'] ?? '' ),
			'aka'   => array_values( (array) ( $d['aka'] ?? [] ) ),
			'links' => promen_steel_analog_links( (array) ( $d['cat'] ?? [] ) ),
		];
	}
	usort( $grades, static fn( $a, $b ) => array_search( $a['g'], $groups, true ) <=> array_search( $b['g'], $groups, true ) );
	return $grades;
}

/** Марка по идентификатору адреса (null — нет такой). */
function promen_steel_analog_find( string $id ): ?array {
	foreach ( promen_steel_analog_grades() as $g ) {
		if ( $g['id'] === $id ) {
			return $g;
		}
	}
	return null;
}

/** Данные для скрипта страницы. */
function promen_steel_analog_bootstrap(): array {
	$q = [];
	foreach ( promen_steel_analog_q() as $k => $v ) {
		$q[ $k ] = $v['label'];
	}
	return [
		'grades'  => promen_steel_analog_grades(),
		'systems' => promen_steel_analog_systems(),
		'groups'  => promen_steel_analog_groups(),
		'q'       => $q,
		'chem'    => promen_steel_foreign_chem(),
		'known'   => promen_steel_analog_known(),
	];
}
