		'teploelektrocentral-tec-3' => 'img/projects/tec3.png',
		'aes-ruppur'                => 'img/projects/rupp.png',
		'aes-akkuyu'                => 'img/projects/turk2.png',
	];
	$promen_img_dir = __DIR__ . '/../assets/img/projects/';
	foreach ( $r as &$promen_reg_item ) {
		$promen_reg_slug = $promen_reg_item['slug'];
		if ( file_exists( $promen_img_dir . $promen_reg_slug . '.webp' ) ) {
			$promen_reg_item['photo'] = 'img/projects/' . $promen_reg_slug . '.webp';
		} elseif ( isset( $promen_legacy_photos[ $promen_reg_slug ] ) ) {
			$promen_reg_item['photo'] = $promen_legacy_photos[ $promen_reg_slug ];
		}
	}
	unset( $promen_reg_item );

	$cache = $r;
	return $cache;
}

/**
 * Адрес раздела каталога или страницы норматива по слагу термина.
 * Пустая строка, если термина нет: ссылку тогда просто не выводим.
 *
 * @param string $taxonomy norm | product_cat.
 */
function promen_project_term_url( string $taxonomy, string $slug ): string {
	$term = $slug ? get_term_by( 'slug', $slug, $taxonomy ) : false;
	if ( ! $term ) {
		return '';
	}
	$url = get_term_link( $term );
	return is_wp_error( $url ) ? '' : (string) $url;
}

/**
 * Ссылка «в каталог» у карточки объекта без детальной страницы.
 * link = [ подпись, таксономия (norm | product_cat), слаг термина ].
 *
 * @param array{0:string,1:string,2:string} $link
 */
function promen_project_link_url( array $link ): string {
	return promen_project_term_url( $link[1] ?? '', $link[2] ?? '' );
}
