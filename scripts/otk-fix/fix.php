/* -------------------------------------------------------------- нормализация */

function otk_norm( $s ) {
	$s = mb_strtolower( trim( (string) $s ), 'UTF-8' );
	$s = str_replace( 'ё', 'е', $s );
	$s = preg_replace( '~^(гост\s*р?|гост|ост|сто\s*цкти|сто\s*сро-п|сто|серия|gost\s*r?|gost|ost|sto|seriya)[\s._-]*~u', '', $s );
	$s = str_replace( [ '_', '.', ' ' ], [ '-', '-', '-' ], $s );
	$s = trim( preg_replace( '~-+~', '-', $s ), '-' );
	return preg_replace( '~-(19|20)(\d\d)$~', '-$2', $s );
}

/** Ключ норматива без года: 34-10-764-97 => 34-10-764. */
function otk_core( $n ) {
	return preg_replace( '~-\d\d$~', '', $n );
}

/* ------------------------------------------------------------------- работа */

global $wpdb;
$report = [];
$moves  = [];   // старый слаг => новый
$gone   = [];   // удалённые слаги
$needs  = [];   // нужен размер руками

$ids = $wpdb->get_col( "SELECT ID FROM {$wpdb->posts} WHERE post_type='product' AND post_status='publish'" );
echo 'товаров: ' . count( $ids ) . ( $DRY ? "  (ПРОГОН, без записи)\n" : "  (ЗАПИСЬ)\n" );

foreach ( $ids as $pid ) {
	$post = get_post( $pid );
	if ( ! $post ) {
		continue;
	}
	$slug = $post->post_name;

	/* --- 1. удаление согласованных позиций --- */
	if ( in_array( $slug, $DELETE, true ) ) {
		$gone[] = $slug;
		$report[] = [ $pid, $slug, 'delete', 'нет в нормативе' ];
		if ( ! $DRY ) {
			wp_delete_post( $pid, true );
		}
		continue;
	}

	$norm = (string) get_post_meta( $pid, '_promen_norm_key', true );
	$core = otk_core( otk_norm( $norm ) );
	$dims = json_decode( (string) get_post_meta( $pid, '_promen_dims', true ), true );
	$dims = is_array( $dims ) ? $dims : [];

	$title   = $post->post_title;
	$content = $post->post_content;
	$newslug = $slug;
	$changed = [];

	/* --- 2. род изделия --- */
	if ( isset( $KIND[ $core ] ) ) {
		list( $head, $phrase ) = $KIND[ $core ];

		// заголовок: первое слово
		if ( preg_match( '~^(\S+)~u', $title, $m ) && mb_strtolower( $m[1], 'UTF-8' ) !== mb_strtolower( $head, 'UTF-8' ) ) {
			$title = $head . mb_substr( $title, mb_strlen( $m[1], 'UTF-8' ), null, 'UTF-8' );
			$changed[] = 'заголовок';
			// слаг под новый род изделия
			$root = $SLUG_ROOT[ $head ] ?? '';
			if ( $root && preg_match( '~^([a-z]+)~', $slug, $ms ) && $ms[1] !== $root ) {
				$newslug = $root . substr( $slug, strlen( $ms[1] ) );
				$changed[] = 'слаг';
			}
		}

		// описание: фраза до « по »
		if ( preg_match( '~^(.+?)\s+по\s+~u', $content, $m ) && $m[1] !== $phrase ) {
			$content = $phrase . mb_substr( $content, mb_strlen( $m[1], 'UTF-8' ), null, 'UTF-8' );
			$changed[] = 'описание';
		}
	}

	/* --- 3. ложная равнопроходность ---
	 * Переход равнопроходным не бывает по определению, поэтому для категории
	 * «Переходы» правило шире списка нормативов на переходные изделия. */
	$is_reducer_cat = has_term( 'perekhody', 'product_cat', $pid );
	if ( ( in_array( $core, $ONLY_REDUCING, true ) || $is_reducer_cat )
		&& ( $dims['equal_pass'] ?? '' ) === 'да' ) {
		unset( $dims['equal_pass'], $dims['outer_d_branch'], $dims['wall_branch'] );
		$changed[] = 'снята равнопроходность';
		$needs[] = [ $pid, $newslug, $norm, $dims['outer_diameter'] ?? '', $dims['wall_thickness'] ?? '' ];
		// «Размеры 57х3-57х3 мм» -> «Размеры 57х3 мм».
		// Разделитель в данных встречается тремя видами: кириллическая «х»,
		// латинская «x» и знак умножения «×» — ловим все, иначе часть строк
		// молча остаётся с выдуманной парой.
		$X = '[хx\x{00D7}]';
		$content = preg_replace( '~(Размеры\s+)([\d.,]+' . $X . '[\d.,]+)-\2(\s*мм)~u', '$1$2$3', $content );
		$title   = preg_replace( '~([\d.,]+' . $X . '[\d.,]+)-\1~u', '$1', $title );
		// Условное обозначение вида «К-1-23х3-23х3» несёт ту же выдуманную пару.
		if ( ! empty( $dims['gost_designation'] ) ) {
			$dims['gost_designation'] = preg_replace(
				'~([\d.,]+' . $X . '[\d.,]+)-\1~u', '$1', $dims['gost_designation'] );
		}
		$content = preg_replace( '~(обозначение:\s*\S*?)([\d.,]+' . $X . '[\d.,]+)-\2~u', '$1$2', $content );
		if ( ! isset( $KIND[ $core ] ) ) {
			$changed[] = 'описание';
		}
	}

	/* --- 3b. схлопывание выдуманной пары ---
	 * Отдельным правилом, а не внутри проверки equal_pass: флаг снимается на
	 * первом же проходе, а «23×3-23×3» остаётся в заголовке и обозначении. */
	$X = '[хx\x{00D7}]';
	$pair = '~([\d.,]+' . $X . '[\d.,]+)-\1(?![\d,.])~u';
	$t2 = preg_replace( $pair, '$1', $title );
	if ( $t2 !== $title ) {
		$title = $t2;
		$changed[] = 'схлопнута пара в заголовке';
	}
	if ( ! empty( $dims['gost_designation'] ) ) {
		$g2 = preg_replace( $pair, '$1', $dims['gost_designation'] );
		if ( $g2 !== $dims['gost_designation'] ) {
			$dims['gost_designation'] = $g2;
			$changed[] = 'схлопнута пара в обозначении';
		}
	}
	$c2 = preg_replace( $pair, '$1', $content );
	if ( $c2 !== $content ) {
		$content = $c2;
		$changed[] = 'схлопнута пара в описании';
	}

	/* --- 3d. пара «Dн - тот же Ду» в заголовке ---
	 * «Тройник 1020х10-1000х10» читается как переход 1020→1000, а это один и тот
	 * же трубопровод: 1020 — наружный диаметр, 1000 — его условный проход.
	 * Сводим второй элемент по сортаменту и, если он совпал с первым, убираем. */
	static $DU2DN = [
		6 => 10, 10 => 14, 15 => 18, 20 => 25, 25 => 32, 32 => 38, 40 => 45, 50 => 57,
		65 => 76, 80 => 89, 100 => 108, 125 => 133, 150 => 159, 200 => 219, 250 => 273,
		300 => 325, 350 => 377, 400 => 426, 500 => 530, 600 => 630, 700 => 720,
		800 => 820, 900 => 920, 1000 => 1020, 1200 => 1220, 1400 => 1420, 1600 => 1620,
	];
	$X2 = '[хx\x{00D7}]';
	if ( preg_match( '~([\d.,]+)' . $X2 . '([\d.,]+)-([\d.,]+)' . $X2 . '([\d.,]+)~u', $title, $mm ) ) {
		$a = (float) str_replace( ',', '.', $mm[1] );
		$b = (float) str_replace( ',', '.', $mm[3] );
		$b_dn = $DU2DN[ (int) round( $b ) ] ?? $b;
		if ( abs( $a - $b_dn ) < 0.01 ) {
			$title   = str_replace( $mm[0], $mm[1] . '×' . $mm[2], $title );
			$content = preg_replace( '~(Размеры\s+)' . preg_quote( $mm[1], '~' ) . $X2 . preg_quote( $mm[2], '~' )
				. '-' . preg_quote( $mm[3], '~' ) . $X2 . preg_quote( $mm[4], '~' ) . '~u',
				'$1' . $mm[1] . 'х' . $mm[2], $content );
			$changed[] = 'снят Ду, выданный за второй конец';
		}
	}

	/* --- 3c. равный условный проход отвода ---
	 * У переходного тройника Ду отвода не может совпадать с Ду корпуса. Такая
	 * пара — след того же дублирования, что и D×s, и она отдельно попадает в
	 * реестр каталога колонкой «DN/DN2». */
	if ( in_array( $core, $ONLY_REDUCING, true ) || $is_reducer_cat ) {
		foreach ( [ [ 'dn', 'dn_branch' ], [ 'dy', 'dy1' ] ] as $p ) {
			if ( isset( $dims[ $p[0] ], $dims[ $p[1] ] ) && $dims[ $p[0] ] === $dims[ $p[1] ] ) {
				unset( $dims[ $p[1] ] );
				$changed[] = 'снят равный Ду отвода';
			}
		}
	}

	/* --- 3a. код типа изделия ---
	 * product_type управляет фильтрами каталога и подбором снимка, поэтому
	 * бобышка с кодом «ЗЭ» (эллиптическая заглушка) ломает и то, и другое. */
	static $PTYPE = [
		'34-10-428' => 'ЗФ', '34-42-666' => 'ЗП', '24-125-22' => 'ББ', '24-125-57' => 'ББ',
		'24-125-23' => 'ПР', '24-125-11' => 'ШТ', '24-125-12' => 'ШТ',
		'34-10-509' => 'ШТ', '34-10-761' => 'ШТ', '34-42-670' => 'ШТ',
		'24-125-21' => 'ДН', '24-125-53' => 'ДН',
	];
	if ( isset( $PTYPE[ $core ] ) && ( $dims['product_type'] ?? '' ) !== $PTYPE[ $core ] ) {
		$dims['product_type'] = $PTYPE[ $core ];
		$changed[] = 'код типа';
	}

	/* --- 4. стенка >= D/2 --- */
	$od = (float) str_replace( ',', '.', (string) ( $dims['outer_diameter'] ?? '' ) );
	$wt = (float) str_replace( ',', '.', (string) ( $dims['wall_thickness'] ?? '' ) );
	if ( $od > 0 && $wt > 0 && $wt >= $od / 2 ) {
		unset( $dims['wall_thickness'] );
		$changed[] = 'снята недостоверная стенка';
		$content = preg_replace( '~\s*Толщина стенки T [\d.,]+ мм\.~u', '', $content );
		$needs[] = [ $pid, $newslug, $norm, $od, 'стенка снята' ];
	}

	/* --- 5. мусор в условном проходе ---
	 * В dn/dn_branch/dy/dy1 у СДТ попадали наружный диаметр («DN 137» у днища
	 * D137), обрывки обозначения («DN 09», «DN 03») и склейки («DN 1030»).
	 * Где известен наружный диаметр — восстанавливаем Ду по сортаменту, иначе
	 * поле убираем: пустое место честнее выдуманного прохода.
	 *
	 * Крепёж не трогаем: там в dn лежит диаметр резьбы, и это не ошибка.
	 */
	$is_fastener = isset( $dims['thread_size'] ) || isset( $dims['washer_type'] )
		|| ( function_exists( 'promen_product_is_fastener' ) && promen_product_is_fastener( $pid ) );
	if ( ! $is_fastener ) {
		static $DN_ROW = [
			6, 8, 10, 15, 20, 25, 32, 40, 50, 65, 80, 100, 125, 150, 175, 200, 250,
			300, 350, 400, 450, 500, 600, 700, 800, 900, 1000, 1100, 1200, 1400,
			1600, 1800, 2000,
		];
		// Наружный диаметр -> условный проход. Два ряда: ГОСТ 8732/10704 и ISO
		// (ГОСТ 17375/17376 — 21,3 / 26,9 / 33,7 …).
		static $DN2DU = [
			'10' => 6, '14' => 10, '18' => 15, '25' => 20, '32' => 25, '38' => 32,
			'45' => 40, '57' => 50, '76' => 65, '89' => 80, '108' => 100, '133' => 125,
			'159' => 150, '219' => 200, '273' => 250, '325' => 300, '377' => 350,
			'426' => 400, '530' => 500, '630' => 600, '720' => 700, '820' => 800,
			'920' => 900, '1020' => 1000, '1220' => 1200, '1420' => 1400, '1620' => 1600,
			'21.3' => 15, '26.9' => 20, '33.7' => 25, '42.4' => 32, '48.3' => 40,
			'60.3' => 50, '88.9' => 80, '114.3' => 100, '168.3' => 150, '219.1' => 200,
			'273.1' => 250, '323.9' => 300, '355.6' => 350, '406.4' => 400, '508' => 500,
		];
		/*
		 * У детали с одним проходом (нет второго торца) условный проход
		 * однозначно следует из наружного диаметра. Тогда сортамент — источник
		 * истины, даже если в поле лежит формально допустимое число: «Тройник
		 * 219х9 Dy06» и «Фланец ФП DN06» получили в DN номер исполнения, а 6 —
		 * настоящий проход из ряда, и проверкой «есть в ряду» такое не поймать.
		 * У переходных изделий так делать нельзя: там dn относится к корпусу, а
		 * outer_diameter может описывать трубу штуцера.
		 */
		$single_bore = ! isset( $dims['outer_d_branch'] ) && ! isset( $dims['dn_branch'] )
			&& ! isset( $dims['dy1'] );

		$fix_dn = static function ( $val, $od ) use ( $DN_ROW, $DN2DU, $single_bore ) {
			$v = trim( (string) $val );
			if ( '' === $v ) {
				return null;                       // нечего чинить
			}
			$k0 = rtrim( rtrim( str_replace( ',', '.', trim( (string) $od ) ), '0' ), '.' );
			if ( $single_bore && '' !== $k0 && isset( $DN2DU[ $k0 ] ) ) {
				return (string) $DN2DU[ $k0 ];     // проход выводится из диаметра
			}
			$n = (float) str_replace( ',', '.', $v );
			if ( in_array( (int) round( $n ), $DN_ROW, true ) && abs( $n - round( $n ) ) < 1e-6 ) {
				return ltrim( $v, '0' ) !== '' ? (string) (int) round( $n ) : $v;
			}
			$k = rtrim( rtrim( str_replace( ',', '.', trim( (string) $od ) ), '0' ), '.' );
			if ( '' !== $k && isset( $DN2DU[ $k ] ) ) {
				return (string) $DN2DU[ $k ];      // восстановили по сортаменту
			}
			return false;                          // убрать
		};

		foreach ( [ [ 'dn', 'outer_diameter' ], [ 'dy', 'outer_diameter' ],
			[ 'dn_branch', 'outer_d_branch' ], [ 'dy1', 'outer_d_branch' ] ] as $pair ) {
			if ( ! isset( $dims[ $pair[0] ] ) ) {
				continue;
			}
			$res = $fix_dn( $dims[ $pair[0] ], $dims[ $pair[1] ] ?? '' );
			if ( null === $res || $res === $dims[ $pair[0] ] ) {
				continue;
			}
			if ( false === $res ) {
				unset( $dims[ $pair[0] ] );
				$changed[] = 'убран мусорный ' . $pair[0];
			} else {
				$dims[ $pair[0] ] = $res;
				$changed[] = 'восстановлен ' . $pair[0];
			}
		}
		/*
		 * Те же числа лежат в описании текстом. Правим отдельно от dims: у части
		 * карточек поле уже вычищено прошлым проходом, а текст остался — если
		 * ориентироваться только на изменение dims, такие описания не тронутся.
		 * Точку удаляем вместе с числом, иначе остаётся висячее « . ».
		 */
		$before = $content;
		$dn_now = trim( (string) ( $dims['dn'] ?? '' ) );
		$dn2_now = trim( (string) ( $dims['dn_branch'] ?? '' ) );
		$content = preg_replace(
			'~\s*\bDN (\d+(?:[.,]\d+)?)\.?~u',
			'' !== $dn_now ? ' DN ' . $dn_now . '.' : '',
			$content, 1 );
		$content = preg_replace(
			'~\s*\bDN1 (\d+(?:[.,]\d+)?)\.?~u',
			'' !== $dn2_now ? ' DN1 ' . $dn2_now . '.' : '',
			$content, 1 );
		$content = preg_replace( '~\s+([.,])~u', '$1', $content );
		// Удвоенная точка — след предыдущего прохода, где число убрали, а точку
		// от него оставили: «Исполнение 10. . Наружный» -> «10..».
		$content = preg_replace( '~\.{2,}~u', '.', $content );
		$content = trim( preg_replace( '~\s{2,}~u', ' ', $content ) );
		if ( $content !== $before ) {
			$changed[] = 'DN в описании';
		}
	}

	if ( ! $changed ) {
		continue;
	}

	$report[] = [ $pid, $slug, implode( '+', array_unique( $changed ) ), $title ];
	if ( $newslug !== $slug ) {
		$moves[ $slug ] = $newslug;
	}

	if ( ! $DRY ) {
		$upd = [ 'ID' => $pid ];
		if ( $title !== $post->post_title ) {
			$upd['post_title'] = $title;
		}
		if ( $content !== $post->post_content ) {
			$upd['post_content'] = $content;
		}
		if ( $newslug !== $slug ) {
			$upd['post_name'] = $newslug;
		}
		if ( count( $upd ) > 1 ) {
			wp_update_post( $upd );
		}
		update_post_meta( $pid, '_promen_dims', wp_json_encode( $dims, JSON_UNESCAPED_UNICODE ) );
	}
}

/* ------------------------------------------------------------------ отчёты */

$w = function ( $name, $rows ) use ( $DIR ) {
	$fh = fopen( $DIR . '/' . $name, 'w' );
	foreach ( $rows as $r ) {
		fwrite( $fh, implode( "\t", (array) $r ) . "\n" );
	}
	fclose( $fh );
};

$w( 'report.tsv', $report );
$w( 'needs-size.tsv', $needs );
$w( 'moves.tsv', array_map( null, array_keys( $moves ), array_values( $moves ) ) );
$w( 'gone.tsv', array_map( fn( $s ) => [ $s ], $gone ) );

printf( "изменено: %d | смена слага: %d | удалено: %d | нужен размер руками: %d\n",
	count( $report ), count( $moves ), count( $gone ), count( $needs ) );
