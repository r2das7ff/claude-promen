/**
 * Правки каталога по замечаниям ОТК (2026-09-10).
 *
 * Запуск:
 *   docker compose run --rm wpcli eval-file /scripts/otk-fix/fix.php --dry
 *   docker compose run --rm wpcli eval-file /scripts/otk-fix/fix.php --apply
 *
 * Что делает:
 *   1. Правит род изделия в заголовке, описании и слаге там, где он не совпадает
 *      с нормативом (бобышки, пробки, штуцеры, донышки, фланцевые заглушки).
 *   2. Снимает ложную равнопроходность у изделий, чей норматив — только на
 *      переходные. Выдуманный второй конец удаляется, а не заменяется догадкой.
 *   3. Чистит толщину стенки там, где она >= D/2 (в поле стенки лежал другой размер).
 *   4. Удаляет три позиции, которых нет в нормативе.
 *   5. Пишет карту 301 для сменившихся слагов и список 410 для удалённых.
 *
 * Второй типоразмер НЕ восстанавливается догадкой: в слагах он записан то
 * наружным диаметром, то условным проходом, и часть слагов несёт тот же самый
 * диаметр в двух видах. Список позиций, которым размер нужно проставить руками
 * по таблице норматива, выгружается в needs-size.tsv.
 */

